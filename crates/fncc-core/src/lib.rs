pub mod codegen;
pub mod config;
pub mod parser;

pub use parser::parse;

use std::path::Path;

/// Main entry point: parse all .fui files under `ui_dir` and write
/// generated Rust code into `out_file`.
pub fn generate_all(ui_dir: &Path, out_file: &Path) {
    let mut output = String::new();
    output.push_str("// Generated by fncc-core. Do not edit.\n\n");

    let entries = std::fs::read_dir(ui_dir).expect("failed to read ui dir");
    for entry in entries {
        let entry = entry.expect("failed to read entry");
        let path = entry.path();
        if path.extension().is_some_and(|ext| ext == "fui") {
            let source = std::fs::read_to_string(&path).unwrap_or_else(|_| panic!("failed to read {:?}", path));
            let ast = parser::parse(&source).unwrap_or_else(|_| panic!("failed to parse {:?}", path));
            let generated = codegen::generate(&ast);
            output.push_str(&generated);
            output.push('\n');
        }
    }

    std::fs::write(out_file, &output).expect("failed to write generated file");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_generate_all_creates_output_file() {
        let dir = std::env::temp_dir().join(format!("fncc_test_{}", std::process::id()));
        let ui_dir = dir.join("ui");
        std::fs::create_dir_all(&ui_dir).unwrap();
        std::fs::write(ui_dir.join("App.fui"), "<Text>hello</Text>").unwrap();
        let out_file = dir.join("out.rs");

        generate_all(&ui_dir, &out_file);

        assert!(out_file.exists());
        let content = std::fs::read_to_string(&out_file).unwrap();
        assert!(content.contains("// Generated by fncc-core. Do not edit."));
        assert!(content.contains("pub fn render_text()"));
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn test_generate_all_ignores_non_fui_files() {
        let dir = std::env::temp_dir().join(format!("fncc_test_{}", std::process::id()));
        let ui_dir = dir.join("ui");
        std::fs::create_dir_all(&ui_dir).unwrap();
        std::fs::write(ui_dir.join("App.fui"), "<A></A>").unwrap();
        std::fs::write(ui_dir.join("notes.txt"), "not a fui").unwrap();
        std::fs::write(ui_dir.join("main.rs"), "fn main() {}").unwrap();
        let out_file = dir.join("out.rs");

        generate_all(&ui_dir, &out_file);

        let content = std::fs::read_to_string(&out_file).unwrap();
        assert!(content.contains("render_a"));
        assert!(!content.contains("notes"));
        assert!(!content.contains("main"));
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
